-- 依据成绩统一结算已修学分（及格课程的学分之和）
UPDATE sms_students s
SET s.Scredits = (
    SELECT COALESCE(SUM(l.Lcredits), 0)
    FROM sms_grades g
    JOIN sms_lesson l ON g.Lno = l.Lno
    WHERE g.Sno = s.Sno AND g.grade >= 60
);

